"""Render the Devpost entry report markdown, formerly committed as docs/findings.md.

The document follows the exact Devpost 2026 structure: question asked, what
we did, what we found (numbered F1 to F5 with the actual numbers from this
run), limitations. Every figure is read from the findings dict so the report
can never drift from public/data/findings.json.
"""

from __future__ import annotations

import calendar
from typing import Any

from scripts.analysis.ledger import SYNTHETIC_NOTICE, signed_dollars
from scripts.generate_mock_ledger import DEFAULT_SEED
from scripts.pipeline_lib import cents_to_dollars

REPRODUCE: str = """```bash
uv sync
uv run python -m scripts.analysis.build_findings
uv run python -m scripts.analysis.verify_findings
uv run pytest
```"""


def _pct(value: float, digits: int = 2) -> str:
    """Format a 0..1 share as a percentage string."""
    return f"{value * 100:.{digits}f}%"


def _f3(value: float) -> str:
    """Format a metric such as an AUC to three decimals."""
    return f"{value:.3f}"


def _f2(value: float) -> str:
    """Format a ratio such as a lift to two decimals."""
    return f"{value:.2f}"


def _f1pct(value: float) -> str:
    """Format a deviation as a whole percentage."""
    return f"{value * 100:.0f}%"


def render_report(findings: dict[str, Any]) -> str:
    """Build the full markdown document from one findings dict."""
    f1 = findings["f1StructuralVsDiscretionary"]
    f2 = findings["f2Seasonality"]
    f3 = findings["f3DeficitRisk"]
    f4 = findings["f4PlaneChangeCost"]
    f5 = findings["f5Interventions"]
    headline = findings["headline"]
    meta = findings["meta"]

    n1 = f1["numbers"]
    n2 = f2["numbers"]
    n3 = f3["numbers"]
    n4 = f4["numbers"]
    n5 = f5["numbers"]

    lines: list[str] = []
    add = lines.append

    add("# Ledger Odyssey: what one year of a Tangerine style ledger actually says")
    add("")
    add(f"> **SYNTHETIC DATA NOTICE: every number below comes from a synthetic mock "
        f"ledger.** Source: `{meta['sources']['world']['sourceCsvPath']}`, generated by "
        f"`scripts/generate_mock_ledger.py` with seed `{DEFAULT_SEED}` "
        f"({meta['sources']['transactions']['rowCount']:,} rows, "
        f"{meta['dateRange']['start']} to {meta['dateRange']['end']}, Tangerine style "
        f"schema). No real bank statements are used anywhere in this repository. "
        f"Every method here transfers unchanged to the real Tangerine dataset: "
        f"only the input CSV path changes, because scripts/build_world.py already "
        f"consumes either file.")
    add("")
    add("## The question we asked")
    add("")
    add("Of one year of Tangerine style transactions, how much spending is locked by "
        "the calendar rather than by choice, when does the balance actually run out, "
        "and what would it cost to move spending onto the payday cycle? The 2026 "
        "rubric weights Discovery at 35 and Data Use at 25, so this entry leads with "
        "the findings; the orbit game below them is the exploration layer over the "
        "same numbers.")
    add("")
    add("## What we did")
    add("")
    add("| Step | What ran | Artifact |")
    add("|------|----------|----------|")
    add("| 1. Build | `scripts/build_world.py` turns the CSV into a row table plus a game world, stamping per entity provenance (row ids, filter, aggregation, SHA256 checksum) | `public/data/world.json`, `public/data/transactions.json` |")
    add("| 2. F1 structural share | Day of week and holiday deseasonalized lag autocorrelation at lags 28 to 35 per category, thresholded against a white noise band and control lags 50 to 180 | `findings.json` f1 |")
    add("| 3. F2 seasonality | Day of week, month, and holiday window decomposition with declared verdict thresholds | `findings.json` f2 |")
    add("| 4. F3 risk model | L2 logistic regression on night before features (trailing "
        f"windows end at t minus 1), time ordered split at "
        f"{n3['splitDate']}, C selected by time ordered CV inside the train window, "
        "model card emitted | `public/data/model_card.json` |")
    add("| 5. F4 plane change cost | Counterfactual timing simulation of every category against the income phase, three scenarios each | `findings.json` f4 |")
    add("| 6. F5 interventions | Four simulated counterfactuals ranked by floor lift then drawdown improvement | `findings.json` f5 |")
    add("| 7. Verify | `scripts/analysis/verify_findings.py` recomputes every number and compares against the files, mirroring the pipeline checksum discipline; `uv run pytest` wraps it | exit code 0 |")
    add("")
    add("Seeds and versions: mock ledger seed "
        f"`{meta['seed']}`, scikit-learn `random_state {n3['randomSeed']}`, "
        "dependencies pinned in `pyproject.toml` with `uv.lock`.")
    add("")
    add("## What we found")
    add("")

    add(f"### F1: only {_pct(n1['structuralShareOfAnnualSpend'])} of annual spend is structural "
        f"(calendar locked); {_pct(n1['discretionaryShareOfAnnualSpend'])} is discretionary")
    add("")
    add(f"Question: {f1['question']}")
    add("")
    struct_names = ", ".join(n1["structuralCategories"])
    disc_names = ", ".join(n1["discretionaryCategories"])
    add(f"We built one daily spend series per category over {meta['dateRange']['start']} "
        f"to {meta['dateRange']['end']}, removed the day of week mean effect and the "
        f"holiday window mean effect (so weekly rhythm and the one holiday level shift "
        f"cannot masquerade as monthly recurrence), then tested lag autocorrelation at "
        f"lags {n1['lagWindowDays'][0]} to {n1['lagWindowDays'][1]} against both a "
        f"white noise band and the category's own control lags. "
        f"**{struct_names} are structural; {disc_names} are discretionary.**")
    add("")
    add("| Category | Annual spend | Peak acf (lag 28 to 35) | Threshold | Classification |")
    add("|----------|-------------|--------------------------|-----------|----------------|")
    for row in f1["categories"]:
        add(f"| {row['name']} | ${cents_to_dollars(int(row['annualSpendCents']))} | "
            f"{_f3(row['peakAcf'])} at lag {row['peakLag']} | {_f3(row['threshold'])} | "
            f"{row['classification']} |")
    add("")
    add(f"So what: the persona's problem is behavioral, not structural. The dollar "
        f"total that survives the recurrence test is only "
        f"${cents_to_dollars(int(n1['structuralSpendCents']))} out of "
        f"${cents_to_dollars(int(n1['totalAnnualSpendCents']))}. {f1['limitations'][1]}")
    add("")

    add(f"### F2: seasonality is {headline['seasonalityVerdict']}")
    add("")
    add(f"Question: {f2['question']}")
    add("")
    add(f"Every category's spend is split into 7 day of week shares, 12 ledger month "
        f"shares, and the {n2['holidayWindowDays']} day holiday window share, each "
        f"compared against the share of days it covers. Verdict rules: holiday lift at "
        f"or above {n2['holidayLiftThreshold']} is calendar driven; weekly deviation "
        f"(weekend share versus its 2/7 calendar baseline) at or above "
        f"{n2['weeklyDeviationThreshold']} is behavioral and needs at least "
        f"{n2['minimumWeeklyRows']} debit rows so sparse weekday noise cannot "
        f"qualify; both is mixed; neither is weak.")
    add("")
    add("| Category | Weekend share vs calendar | Holiday lift | Weekly deviation | Verdict |")
    add("|----------|---------------------------|--------------|------------------|---------|")
    for row in f2["categories"]:
        add(f"| {row['name']} | {_pct(row['weekendShare'], 1)} vs {_pct(row['weekendCalendarShare'], 1)} "
            f"({row['weekendLift']:.2f}x) | {row['holidayWindow']['lift']:.2f}x | "
            f"{_f1pct(row['weeklyDeviation'])} | {row['verdict']} |")
    add("")
    unreliable = [
        str(row["name"]) for row in f2["categories"] if not row["weeklyPatternReliable"]
    ]
    add(f"Plain language: {n2['strongestCalendarCategory']} is the most calendar driven "
        f"({n2['strongestCalendarLift']:.2f} times its holiday calendar share) and "
        f"{n2['strongestBehavioralCategory']} is the most behavioral (weekend deviation "
        f"{_f1pct(n2['strongestBehavioralDeviation'])} away from the 2/7 calendar "
        f"baseline). {n2['verdictSummary']}.")
    if unreliable:
        add("")
        add(f"Note: {', '.join(unreliable)} has fewer than "
            f"{n2['minimumWeeklyRows']} debit rows, so its weekday columns are shown "
            f"for completeness and only the calendar test applies to its verdict.")
    add("")

    add(f"### F3: the deficit day model reaches test AUC {_f3(n3['testAuc'])} "
        f"(accuracy {_pct(n3['accuracyAtHalf'], 1)}, majority baseline {_pct(n3['majorityAccuracy'], 1)})")
    add("")
    add(f"Question: {f3['question']}")
    add("")
    add(f"Target: a deficit day is a day whose closing balance is negative "
        f"(0 CAD threshold, {n3['trainEvents'] + n3['testEvents']} events). The data "
        f"supports this label better than the next day below 1,000 CAD alternative, "
        f"which we also fit as a robustness check (test AUC "
        f"{_f3(n3['robustnessAlternativeTestAuc'])}). Features (every row is known "
        f"the night before day t: trailing windows end at t minus 1, so day t never "
        f"enters its own feature row): trailing 7 and 30 day "
        f"net flow, day of week and month indicators, days since payroll, trailing 30 "
        f"day spend volatility. Time ordered split at {n3['splitDate']} "
        f"({n3['trainDays']} train days with {n3['trainEvents']} events, "
        f"{n3['testDays']} test days with {n3['testEvents']} events); C = "
        f"{n3['selectedC']} chosen by time ordered CV on train only.")
    add("")
    add("| Metric | Value |")
    add("|--------|-------|")
    add(f"| Test AUC (headline) | {_f3(n3['testAuc'])} |")
    add(f"| Train AUC (drift check) | {_f3(n3['trainAuc'])} |")
    add(f"| Accuracy at 0.5 threshold | {_pct(n3['accuracyAtHalf'], 1)} |")
    add(f"| Majority class baseline accuracy | {_pct(n3['majorityAccuracy'], 1)} |")
    add(f"| Confusion (tn, fp, fn, tp) | {n3['confusion']['trueNegative']}, "
        f"{n3['confusion']['falsePositive']}, {n3['confusion']['falseNegative']}, "
        f"{n3['confusion']['truePositive']} |")
    add("")
    add("Top coefficients (standardized, with direction):")
    add("")
    add("| Feature | Coefficient | Direction |")
    add("|---------|-------------|-----------|")
    for row in f3["coefficients"][:5]:
        add(f"| {row['feature']} | {row['standardizedCoefficient']:+.4f} | {row['direction']} |")
    add("")
    top1 = f3["coefficients"][0]
    top2 = f3["coefficients"][1]
    add(f"So what: the strongest signal is {top1['feature']} "
        f"({top1['standardizedCoefficient']:+.4f}: {top1['direction']}), followed by "
        f"{top2['feature']} ({top2['standardizedCoefficient']:+.4f}). The model card in "
        f"`public/data/model_card.json` carries the intended use, the drift limitation, "
        f"the fairness caveats, and the correlation not causation statement.")
    add("")

    best_f4 = n4["bestAlignedCategory"]
    add(f"### F4: the plane change cost, aligning {best_f4} to the income phase "
        f"buys ${cents_to_dollars(int(n4['bestAlignedDrawdownImprovementCents']))} of drawdown "
        f"({headline['bestAlignedDrawdownPctOfBaseline']:.1f} percent of the "
        f"${cents_to_dollars(int(n4['baseline']['drawdownCents']))} baseline drawdown) and lifts "
        f"the true trough by ${cents_to_dollars(int(n4['bestAlignedTroughLiftCents']))}")
    add("")
    add(f"Question: {f4['question']}")
    add("")
    add(f"Definition (exact): {f4['definition']}")
    add("")
    add("| Category | Aligned drawdown improvement | Aligned trough lift | Aligned floor delta | Anti aligned floor delta |")
    add("|----------|------------------------------|---------------------|---------------------|--------------------------|")
    for row in f4["categories"]:
        add(f"| {row['name']} | {signed_dollars(int(row['aligned']['drawdownImprovementCents']))} | "
            f"{signed_dollars(int(row['aligned']['troughDeltaCents']))} | "
            f"{signed_dollars(int(row['aligned']['minMonthEndDeltaCents']))} | "
            f"{signed_dollars(int(row['antiAligned']['minMonthEndDeltaCents']))} |")
    add("")
    # The binding floor month and the trough day are derived from the emitted
    # metrics so the sentence cannot go stale when the data changes.
    binding_point = min(
        f4["chartTwin"]["monthlySeries"],
        key=lambda point: int(point["baselineCents"]),
    )
    binding_month = str(binding_point["month"])
    binding_year, binding_month_number = (int(part) for part in binding_month.split("-"))
    binding_days = calendar.monthrange(binding_year, binding_month_number)[1]
    trough_date = str(n4["baselineTroughDate"])
    trough_day = int(trough_date.split("-")[2])
    add(f"So what: timing buys the trough, not the month end floor. The floor stays at "
        f"{signed_dollars(int(n4['baseline']['minMonthEndCents']))} under every aligned "
        f"scenario because no forward target can escape the end of the binding "
        f"{binding_days} day month ({binding_month}), while the day {trough_day} trough "
        f"({trough_date}) improves by up to "
        f"${cents_to_dollars(int(n4['bestAlignedTroughLiftCents']))}. The reverse direction "
        f"({n4['antiAlignedFloorCategory']} left late) can only game the month end "
        f"sample point ({signed_dollars(int(n4['antiAlignedFloorLiftCents']))}) without "
        f"touching the true low, which is exactly why both metrics ship together. "
        f"{f4['limitations'][0]}")
    add("")

    add("### F5: ranked interventions, the surge cap wins the floor")
    add("")
    add(f"Question: {f5['question']}")
    add("")
    add(f"Ranking rule: {f5['rankingRule']}")
    add("")
    add("| Rank | Intervention | Floor delta | Drawdown improvement | Label |")
    add("|------|--------------|-------------|----------------------|-------|")
    for row in f5["interventions"]:
        add(f"| {row['rank']} | {row['name']} | "
            f"{signed_dollars(int(row['metrics']['minMonthEndDeltaCents']))} | "
            f"{signed_dollars(int(row['metrics']['drawdownImprovementCents']))} | "
            f"simulated counterfactual |")
    add("")
    auto = next(row for row in f5["interventions"] if row["id"] == "auto_save_payday")
    aux = auto["auxiliary"]
    baseline_floor = int(n4["baseline"]["minMonthEndCents"])
    best_floor_gain = int(n5["bestMinMonthEndImprovementCents"])
    realign_row = next(
        row for row in f5["interventions"] if row["id"] == "realign_top_discretionary"
    )
    if int(aux["deficitDaysSimulated"]) < int(aux["deficitDaysBaseline"]):
        deficit_phrase = (
            f"deficit days fall from {aux['deficitDaysBaseline']} to "
            f"{aux['deficitDaysSimulated']}"
        )
    else:
        deficit_phrase = (
            f"deficit days stay at {aux['deficitDaysBaseline']}: the release "
            f"fires on {aux['releasedDays']} days but only reverses the dips "
            f"the saving itself creates (the held reserve funds exactly its "
            f"own shortfall), so no genuine deficit day is covered"
        )
    add(f"Headline: {n5['bestInterventionName']} lifts the minimum month end balance by "
        f"${cents_to_dollars(best_floor_gain)} "
        f"(floor moves from {signed_dollars(baseline_floor)} to "
        f"{signed_dollars(baseline_floor + best_floor_gain)}), "
        f"and {n5['realignCategory']} realignment improves drawdown by "
        f"${cents_to_dollars(int(realign_row['metrics']['drawdownImprovementCents']))}. "
        f"The auto save row is the honest null: on the combined view it moves neither "
        f"metric, while {deficit_phrase} and the reserve ends the year at "
        f"${cents_to_dollars(int(aux['reserveEndCents']))}. {auto['caveat']}")
    add("")
    add("Every row in F5 is a simulated counterfactual: none of these rules was "
        "applied to the observed ledger, and each delta assumes behavior everywhere "
        "else stays fixed.")
    add("")

    add("## Limitations")
    add("")
    seen: set[str] = set()
    for key in (
        "f1StructuralVsDiscretionary",
        "f2Seasonality",
        "f3DeficitRisk",
        "f4PlaneChangeCost",
        "f5Interventions",
    ):
        for item in findings[key]["limitations"]:
            if item not in seen:
                seen.add(item)
                add(f"- {item}")
    add(f"- Data: {SYNTHETIC_NOTICE}")
    add("- Correlation, not causation: every coefficient and every counterfactual "
        "delta is an association or a modeling result inside this ledger, never an "
        "identified causal effect.")
    add("- Reproducibility: pinned dependencies, logged seeds, time ordered split, "
        "and a verification step that recomputes the published numbers from source.")
    add("")
    add("## Reproduce this report")
    add("")
    add(REPRODUCE)
    add("")
    return "\n".join(lines)
