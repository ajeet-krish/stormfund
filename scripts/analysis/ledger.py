"""Ledger loading and shared derivations for the findings analysis pipeline.

Consumes the artifacts built by scripts/build_world.py:

* public/data/transactions.json (compact row table)
* public/data/world.json (entities, provenance, monthly balance series)

All money values are integer CAD cents. Every derivation here is
deterministic and seed free; the only seed in the analysis package is the
scikit-learn random_state, which mirrors the mock ledger seed.
"""

