TRANSACTIONS_PATH: Path = REPO_ROOT / "public" / "data" / "transactions.json"
WORLD_PATH: Path = REPO_ROOT / "public" / "data" / "world.json"
FINDINGS_PATH: Path = REPO_ROOT / "public" / "data" / "findings.json"
MODEL_CARD_PATH: Path = REPO_ROOT / "public" / "data" / "model_card.json"
REPORT_PATH: Path = REPO_ROOT / "docs" / "findings.md"

PAYROLL_HINT: str = "Payroll"
VIRTUAL_PAYDAY: pd.Timestamp = pd.Timestamp("2025-10-25")
ALIGNED_PHASE_MAX: int = 6
AUTOSAVE_PER_PAYDAY_CENTS: int = 100_000
DEFICIT_THRESHOLD_CENTS: int = 0

